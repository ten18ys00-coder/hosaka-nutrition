function u(unit: string, grams: number, basis: string): FoodUnit {
  return { unit, grams, basis };
}

function F(
  id: string,
  name: string,
  category: string,
  state: string,
  v: (number | null)[],
  units: FoodUnit[],
  kana: string,
  note = '',
): Food {
  const per100: Food['per100'] = {};
  ORDER.forEach((k, i) => (per100[k] = v[i] ?? null));
  const serving = units.find((x) => x.unit !== 'g' && x.unit !== 'ml') ?? units[0] ?? u('g', 100, '100g');
  return {
    id,
    name,
    kana,
    category,
    state,
    source: 'mext8',
    verified: false,
    per100,
    units: [u('g', 1, '重量（可食部）'), ...units],
    serving: { label: `${serving.unit}（${serving.grams}g）`, grams: serving.grams },
    note,
    created_at: T,
    updated_at: T,
  };
}

