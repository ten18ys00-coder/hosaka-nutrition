export interface DriEntry {
  ear: number | null; // 推定平均必要量
  rda: number | null; // 推奨量
  ai: number | null; // 目安量
  dgMin: number | null; // 目標量（下限）
  dgMax: number | null; // 目標量（上限、未満）
  ul: number | null; // 耐容上限量
}

export type DriTable = Record<AgeGroup, DriEntry>;

function table(cols: { ear?: S; rda?: S; ai?: S; dgMin?: S; dgMax?: S; ul?: S }): DriTable {
  const out = {} as DriTable;
  AGE_GROUPS.forEach((g, i) => {
    out[g] = {
      ear: cols.ear?.[i] ?? null,
      rda: cols.rda?.[i] ?? null,
      ai: cols.ai?.[i] ?? null,
      dgMin: cols.dgMin?.[i] ?? null,
      dgMax: cols.dgMax?.[i] ?? null,
      ul: cols.ul?.[i] ?? null,
    };
  });
  return out;
}

